#!/usr/bin/env node
/**
 * gate5-elementor.mjs — gates 2 and 5 for an Elementor build, in the real editor.
 *
 *   node gate5-elementor.mjs <wp-admin-url> --cookies session.json --post 13,19,25
 *                            [--visible ".hero__slide,.gallery__image"] [--min-button 110]
 *                            [--chrome path] [--format text|json]
 *
 * Gate 2 (validity): every widget of the page is known to the editor (no missing widget),
 *   nothing renders as an empty placeholder in the preview.
 * Gate 5 (editor fidelity): in the preview iframe, each --visible selector is in flow
 *   (position relative or static), visible and opaque, so the client can edit it; no button
 *   is squeezed under --min-button px (vertical text). Exit 1 on any failure, and also when a
 *   --visible selector matches nothing on any of the pages: an empty match is not a pass.
 *
 * session.json: an array of WordPress auth cookies for a LOCAL administrator, generated by
 * WordPress itself (references/elementor.md, "Gates on Elementor") — no password is typed
 * or stored. Delete the file after the run; the token expires on its own.
 * The editor is heavy: on XAMPP without OPcache one page took 1–2 minutes to become ready.
 */
import fs from 'node:fs';
import { launch } from './capture.mjs';

const args = process.argv.slice(2);
if (!args.length || args.includes('--help') || args.includes('-h')) {
  console.log('usage: node gate5-elementor.mjs <wp-admin-url> --cookies session.json --post 13,19 [--visible ".a,.b"] [--min-button 110] [--chrome path] [--format text|json]\n'
    + 'Gates 2 and 5 in the Elementor editor: known widgets, no empty widget, editable slides/galleries, no squeezed button.');
  process.exit(args.length ? 0 : 2);
}
const opt = { 'min-button': 110, visible: '', format: 'text' };
const pos = [];
for (let i = 0; i < args.length; i++) { if (args[i].startsWith('--')) opt[args[i].slice(2)] = args[++i]; else pos.push(args[i]); }
const admin = (pos[0] || '').replace(/\/$/, '');
if (!admin || !opt.cookies || !opt.post) { console.error('need <wp-admin-url>, --cookies and --post'); process.exit(2); }
const cookies = JSON.parse(fs.readFileSync(opt.cookies, 'utf8'));
const VISIBLE = opt.visible.split(',').map((s) => s.trim()).filter(Boolean);

const expr = `(async () => {
  const t0 = Date.now();
  const ready = () => window.elementor && elementor.documents && elementor.documents.getCurrent() && elementor.$preview
    && elementor.$preview[0].contentDocument && elementor.$preview[0].contentDocument.querySelector('.elementor-element');
  while (!ready()) {
    if (Date.now() - t0 > 240000) return { error: 'editor not ready after 240 s', title: document.title };
    await new Promise(r => setTimeout(r, 1000));
  }
  await new Promise(r => setTimeout(r, 4000));
  const doc = elementor.documents.getCurrent();
  const all = []; const walk = c => { all.push(c); (c.children || []).forEach(walk); }; walk(doc.container);
  const widgets = all.filter(c => c.model && c.model.get('elType') === 'widget').map(c => c.model.get('widgetType'));
  const d = elementor.$preview[0].contentDocument, w = elementor.$preview[0].contentWindow;
  const hidden = [], matched = {};
  for (const s of ${JSON.stringify(VISIBLE)}) {
    const found = d.querySelectorAll(s);
    matched[s] = found.length;
    for (const e of found) {
      const c = w.getComputedStyle(e);
      if (c.visibility !== 'visible' || c.opacity !== '1' || !['relative', 'static'].includes(c.position)) hidden.push(s);
    }
  }
  const buttons = [...d.querySelectorAll('.elementor-widget-button .elementor-button')].map(b => Math.round(b.getBoundingClientRect().width));
  return {
    title: doc.config.settings.settings.post_title || String(doc.id),
    canvas: d.documentElement.clientWidth,
    widgets: widgets.length,
    unknown: [...new Set(widgets)].filter(t => !elementor.widgetsCache[t]),
    empty: d.querySelectorAll('.elementor-widget-empty').length,
    hidden: [...new Set(hidden)],
    matched,
    narrowButtons: buttons.filter(x => x < ${Number(opt['min-button'])}).length,
    buttons: buttons.length,
  };
})()`;

const results = [];
const b = await launch({ chrome: opt.chrome });
try {
  for (const id of String(opt.post).split(',').map((x) => x.trim()).filter(Boolean)) {
    let r;
    try {
      await b.goto(`${admin}/post.php?post=${id}&action=elementor`, { width: 1440, height: 900, cookies, loadTimeoutMs: 240000 });
      r = await b.evaluate(expr);
    } catch (e) { r = { error: e.message.slice(0, 120) }; }
    const problems = r.error ? [r.error] : [
      ...(r.unknown.length ? [`unknown widgets: ${r.unknown.join(', ')}`] : []),
      ...(r.empty ? [`${r.empty} empty widget(s)`] : []),
      ...(r.hidden.length ? [`hidden in the editor: ${r.hidden.join(', ')}`] : []),
      ...(r.narrowButtons ? [`${r.narrowButtons} button(s) under ${opt['min-button']} px`] : []),
    ];
    results.push({ post: id, ok: !problems.length, problems, ...r });
    const seen = r.matched ? Object.entries(r.matched).filter(([, n]) => n).map(([s, n]) => `${s} ×${n}`) : [];
    if (opt.format !== 'json') console.log(`${problems.length ? 'FAIL' : 'ok  '}  post ${id}${r.title ? ` "${r.title}"` : ''}${r.widgets !== undefined ? `: ${r.widgets} widgets, canvas ${r.canvas}px` : ''}${seen.length ? `, checked ${seen.join(', ')}` : ''}${problems.length ? ' · ' + problems.join('; ') : ''}`);
  }
} finally { await b.close(); }
// A --visible selector that matches nothing anywhere is a typo or a renamed class, not a pass.
const unmatched = VISIBLE.filter((s) => !results.some((r) => r.matched && r.matched[s] > 0));
const failed = results.filter((r) => !r.ok).length + (unmatched.length ? 1 : 0);
if (opt.format === 'json') console.log(JSON.stringify({ failed, unmatched, results }, null, 1));
else {
  if (unmatched.length) console.log(`FAIL  --visible matched nothing on any page: ${unmatched.join(', ')}`);
  console.log(failed ? `${failed} failure(s) in the editor` : 'gates 2 and 5 passed in the Elementor editor');
}
process.exit(failed ? 1 : 0);
